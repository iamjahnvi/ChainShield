"use strict";

const fs = require("node:fs");
const path = require("node:path");

const projectRoot = path.resolve(__dirname, "..");

function validateApiBaseUrl(value) {
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error("Pass the production API base URL as the first argument (for example, https://api.example.com/api). ");
  }
  let apiUrl;
  try { apiUrl = new URL(value.trim()); }
  catch { throw new Error("The production API base URL must be a valid HTTPS URL."); }
  if (apiUrl.protocol !== "https:" || apiUrl.username || apiUrl.password || apiUrl.search || apiUrl.hash) {
    throw new Error("The production API base URL must use HTTPS and cannot include credentials, a query, or a fragment.");
  }
  return { base: apiUrl.href.replace(/\/$/, ""), origin: apiUrl.origin };
}

function copyTree(sourceDirectory, destinationDirectory, base, origin) {
  fs.mkdirSync(destinationDirectory, { recursive: true });
  for (const entry of fs.readdirSync(sourceDirectory, { withFileTypes: true })) {
    if (entry.isFile() && entry.name.endsWith(".test.js")) continue;
    const source = path.join(sourceDirectory, entry.name);
    const destination = path.join(destinationDirectory, entry.name);
    if (entry.isDirectory()) {
      copyTree(source, destination, base, origin);
    } else if (entry.name === "config.js") {
      fs.writeFileSync(destination,
        `// Generated by scripts/build-extension.js. Do not put credentials here.\nwindow.CHAINSHIELD_API_BASE_URL = ${JSON.stringify(base)};\n`);
    } else if (entry.name === "manifest.json") {
      const manifest = JSON.parse(fs.readFileSync(source, "utf8"));
      manifest.host_permissions = [`${origin}/*`];
      fs.writeFileSync(destination, `${JSON.stringify(manifest, null, 2)}\n`);
    } else {
      fs.copyFileSync(source, destination);
    }
  }
}

function buildExtension(apiBaseUrl, outputDirectory = path.join(projectRoot, "dist", "extension")) {
  const { base, origin } = validateApiBaseUrl(apiBaseUrl);
  const resolvedOutput = path.resolve(outputDirectory);
  if (resolvedOutput === projectRoot || !resolvedOutput.startsWith(`${projectRoot}${path.sep}`)) {
    throw new Error("The extension output directory must be inside the project workspace.");
  }
  copyTree(path.join(projectRoot, "extension"), resolvedOutput, base, origin);
  return resolvedOutput;
}

if (require.main === module) {
  try {
    const output = buildExtension(process.argv[2]);
    console.log(`Production extension written to ${path.relative(projectRoot, output)}.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

module.exports = { buildExtension, validateApiBaseUrl };
